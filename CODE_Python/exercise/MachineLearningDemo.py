# ======================
# 真实数据：y = x² -2x +1
# ======================
x = [-2, -1, 0, 1, 2, 3]
y_true = [9, 4, 1, 0, 1, 4]

# ======================
# 机器一开始瞎猜 3 个参数
# 目标：a→1, b→-2, c→1
# ======================
a = 0.5  # 猜 x² 的系数
b = 0.3  # 猜 x 的系数
c = 0.2  # 猜常数项

# 学习步长（每次改一点点）
lr = 0.001

# 训练 30000 次
for epoch in range(30001):
    # ======================
    # 1. 机器预测（试错）
    # ======================
    y_pred = [a * xi**2 + b * xi + c for xi in x]

    # ======================
    # 2. 计算误差（数学）
    # ======================
    loss = sum((yp - yt) ** 2 for yp, yt in zip(y_pred, y_true)) / len(x)

    # ======================
    # 3. 计算梯度（怎么改才对）
    # ======================
    da = sum(2 * (yp - yt) * xi**2 for yp, yt, xi in zip(y_pred, y_true, x)) / len(x)
    db = sum(2 * (yp - yt) * xi for yp, yt, xi in zip(y_pred, y_true, x)) / len(x)
    dc = sum(2 * (yp - yt) for yp, yt in zip(y_pred, y_true)) / len(x)

    # ======================
    # 4. 自动修正参数（学习）
    # ======================
    a -= lr * da
    b -= lr * db
    c -= lr * dc

    # ======================
    # 打印学习过程
    # ======================
    if epoch % 3000 == 0:
        print(f"轮次:{epoch:5d} | a={a:.2f} b={b:.2f} c={c:.2f} | 误差={loss:.2f}")

# ======================
# 最终结果
# ======================
print("\n✅ 机器学习完成！")
print(f"最终公式：y = {a:.2f}x² + {b:.2f}x + {c:.2f}")
print("理想公式：y = 1x² -2x +1")